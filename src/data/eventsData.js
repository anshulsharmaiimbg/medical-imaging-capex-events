export const getEventById = (id) => events.find((e) => e.id === id);

export const getUpcomingEvents = () =>
  events.filter((e) => e.status === 'upcoming').sort((a, b) => new Date(a.dateISO) - new Date(b.dateISO));

export const getPastEvents = () =>
  events.filter((e) => e.status === 'past').sort((a, b) => new Date(b.dateISO) - new Date(a.dateISO));

export const getStats = () => ({
  totalEvents: events.length,
  totalAttendees: events.reduce((sum, e) => sum + e.attendees, 0),
  totalExhibitors: events.reduce((sum, e) => sum + e.exhibitors, 0),
  totalCountries: [...new Set(events.map((e) => e.country))].length,
  upcomingCount: events.filter((e) => e.status === 'upcoming').length,
  pastCount: events.filter((e) => e.status === 'past').length,
});
